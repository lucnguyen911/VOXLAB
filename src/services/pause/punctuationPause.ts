import { PunctuationPauses } from "../../types/ui";

export type PunctuationType =
  | "period"
  | "questionExclamation"
  | "colonSemicolon"
  | "comma"
  | "ellipsis"
  | "none";

/**
 * Baseline punctuation pauses (in seconds).
 * NOTE: PERIOD_PAUSE = TUNING REQUIRED (Baseline: 0.5s).
 * Production audio should tune these via user inspector settings (TtsInspector).
 */
export const DEFAULT_PUNCTUATION_PAUSES: PunctuationPauses = {
  comma: 0.2, // 0.2s - Chuẩn Text-to-Speech
  period: 0.6, // 0.6s - Tách câu tự nhiên
  questionExclamation: 0.5, // 0.5s - Chuẩn Text-to-Speech
  colonSemicolon: 0.4, // 0.4s - Giữ mạch nội dung
};

/**
 * Detects the trailing punctuation of a sentence or chunk text.
 * Strips closing quotes, parentheses, brackets before inspecting the punctuation mark.
 */
export function detectTrailingPunctuation(text: string): PunctuationType {
  const trimmed = text.trim();
  if (!trimmed) return "none";

  // Match optional closing quotes/brackets/parentheses at the end of text
  const match = trimmed.match(/([.!?:;,…]+)["'”’»›)\]}]*$/u);
  if (!match) {
    // Also check for 3 dots "..."
    if (/\.\.\.["'”’»›)\]}]*$/u.test(trimmed)) {
      return "ellipsis";
    }
    return "none";
  }

  const punct = match[1];

  // Check ellipsis (… or ...)
  if (punct.includes("…") || punct.length >= 3) {
    return "ellipsis";
  }

  const lastChar = punct[punct.length - 1];
  if (lastChar === "." || lastChar === "。") {
    return "period";
  }
  if (lastChar === "!" || lastChar === "?" || lastChar === "！" || lastChar === "？") {
    return "questionExclamation";
  }
  if (lastChar === ":" || lastChar === ";" || lastChar === "：" || lastChar === "；") {
    return "colonSemicolon";
  }
  if (lastChar === "," || lastChar === "，" || lastChar === "、") {
    return "comma";
  }

  return "none";
}

/**
 * Calculates the target pause in milliseconds for a chunk or boundary.
 *
 * Rules:
 * 1. Punctuation is the SOLE decider of pause durations.
 * 2. If a manual pause [PAUSE {ms}] is explicitly set, it is respected.
 * 3. Paragraph breaks and line breaks DO NOT create additional pause.
 * 4. Technical chunk boundaries without punctuation produce 0 ms pause.
 */
export function getTargetPauseMs(
  text: string,
  config?: Partial<PunctuationPauses>,
  manualPauseMs?: number | "auto"
): number {
  // Explicit user manual pause override takes precedence if explicitly provided as number
  if (typeof manualPauseMs === "number" && manualPauseMs >= 0) {
    return Math.round(manualPauseMs);
  }

  const punctType = detectTrailingPunctuation(text);
  const period = config?.period ?? DEFAULT_PUNCTUATION_PAUSES.period;
  const comma = config?.comma ?? DEFAULT_PUNCTUATION_PAUSES.comma;
  const qe = config?.questionExclamation ?? DEFAULT_PUNCTUATION_PAUSES.questionExclamation;
  const cs = config?.colonSemicolon ?? DEFAULT_PUNCTUATION_PAUSES.colonSemicolon;

  switch (punctType) {
    case "period":
      return Math.round(period * 1000);
    case "questionExclamation":
      return Math.round(qe * 1000);
    case "colonSemicolon":
      return Math.round(cs * 1000);
    case "comma":
      return Math.round(comma * 1000);
    case "ellipsis":
      // Ellipsis uses period duration by default
      return Math.round(period * 1000);
    case "none":
    default:
      // Technical boundary without punctuation produces 0 ms pause
      return 0;
  }
}

/**
 * Calculates the effective silence gap to append between segments, avoiding
 * accumulating trailing silence already present in the model's generated audio.
 *
 * Example:
 * targetPauseMs = 500 ms (period)
 * existingTrailingSilenceMs = 200 ms (generated by model)
 * effectiveSilenceGapMs = max(0, 500 - 200) = 300 ms
 * Total final silence: 200ms + 300ms = 500ms (matches configuration exactly).
 */
export function calculateEffectiveSilenceGapMs(
  targetPauseMs: number,
  existingTrailingSilenceMs = 0
): number {
  const safeTarget = Math.max(0, targetPauseMs);
  const safeExisting = Math.max(0, existingTrailingSilenceMs);
  return Math.max(0, safeTarget - safeExisting);
}

/**
 * Analyzes audio samples to detect existing trailing silence in milliseconds.
 * Scans backward from the end in 10ms windows using RMS energy.
 */
export function detectTrailingSilenceMs(
  samples: Int16Array | Float32Array | number[],
  sampleRate = 44100,
  silenceThresholdRms = 0.006 // ~ -44.4 dB
): number {
  if (!samples || samples.length === 0) return 0;

  const windowSize = Math.max(1, Math.floor(sampleRate * 0.01)); // 10ms
  let silentSamples = 0;

  for (let i = samples.length - 1; i >= 0; i -= windowSize) {
    const start = Math.max(0, i - windowSize + 1);
    let sumSquares = 0;
    const count = i - start + 1;

    for (let j = start; j <= i; j++) {
      let val = samples[j];
      if (samples instanceof Int16Array) {
        val = val / 32768;
      }
      sumSquares += val * val;
    }

    const rms = Math.sqrt(sumSquares / count);
    if (rms < silenceThresholdRms) {
      silentSamples += count;
    } else {
      break;
    }
  }

  return Math.round((silentSamples / sampleRate) * 1000);
}

/**
 * Analyzes audio samples to detect existing leading silence in milliseconds.
 * Scans forward from the beginning in 10ms windows using RMS energy.
 */
export function detectLeadingSilenceMs(
  samples: Int16Array | Float32Array | number[],
  sampleRate = 44100,
  silenceThresholdRms = 0.006 // ~ -44.4 dB
): number {
  if (!samples || samples.length === 0) return 0;

  const windowSize = Math.max(1, Math.floor(sampleRate * 0.01)); // 10ms
  let silentSamples = 0;

  for (let i = 0; i < samples.length; i += windowSize) {
    const end = Math.min(samples.length, i + windowSize);
    let sumSquares = 0;
    const count = end - i;

    for (let j = i; j < end; j++) {
      let val = samples[j];
      if (samples instanceof Int16Array) {
        val = val / 32768;
      }
      sumSquares += val * val;
    }

    const rms = Math.sqrt(sumSquares / count);
    if (rms < silenceThresholdRms) {
      silentSamples += count;
    } else {
      break;
    }
  }

  return Math.round((silentSamples / sampleRate) * 1000);
}

/**
 * Checks if a pauses object matches known legacy default configurations.
 * In early VoxLab builds, Dialogue had:
 * { comma: 0.5, period: 0.5, questionExclamation: 1.0, colonSemicolon: 0.6 }
 * or early drafts had { comma: 0.5, period: 1.0, questionExclamation: 1.0, colonSemicolon: 0.6 }.
 */
export function isLegacyPunctuationPauses(p: unknown): boolean {
  if (!p || typeof p !== "object") return false;
  const pauses = p as Record<string, unknown>;
  const isLegacyDialogue =
    pauses.comma === 0.5 &&
    pauses.period === 0.5 &&
    (pauses.questionExclamation === 1 || pauses.questionExclamation === 1.0) &&
    pauses.colonSemicolon === 0.6;
  const isLegacyUiSample =
    pauses.comma === 0.5 &&
    (pauses.period === 1 || pauses.period === 1.0) &&
    (pauses.questionExclamation === 1 || pauses.questionExclamation === 1.0) &&
    pauses.colonSemicolon === 0.6;
  const isPreviousIntermediate =
    (pauses.comma === 0.3 || pauses.comma === 0.30) &&
    (pauses.period === 0.6 || pauses.period === 0.60) &&
    (pauses.questionExclamation === 0.7 || pauses.questionExclamation === 0.70) &&
    (pauses.colonSemicolon === 0.4 || pauses.colonSemicolon === 0.40);
  return Boolean(isLegacyDialogue || isLegacyUiSample || isPreviousIntermediate);
}

/**
 * Synchronizes and sanitizes punctuation pauses to match canonical TTS defaults
 * (comma: 0.2s, period: 0.6s, questionExclamation: 0.5s, colonSemicolon: 0.4s).
 * If the object matches legacy defaults, it replaces them with the standard TTS defaults.
 * If custom user overrides are present, it preserves them while filling any missing keys with TTS defaults.
 */
export function sanitizePunctuationPauses(rawPauses: unknown): PunctuationPauses {
  if (!rawPauses || typeof rawPauses !== "object" || isLegacyPunctuationPauses(rawPauses)) {
    return { ...DEFAULT_PUNCTUATION_PAUSES };
  }
  const p = rawPauses as Record<string, unknown>;
  return {
    comma: typeof p.comma === "number" && !isNaN(p.comma) ? p.comma : DEFAULT_PUNCTUATION_PAUSES.comma,
    period: typeof p.period === "number" && !isNaN(p.period) ? p.period : DEFAULT_PUNCTUATION_PAUSES.period,
    questionExclamation:
      typeof p.questionExclamation === "number" && !isNaN(p.questionExclamation)
        ? p.questionExclamation
        : DEFAULT_PUNCTUATION_PAUSES.questionExclamation,
    colonSemicolon:
      typeof p.colonSemicolon === "number" && !isNaN(p.colonSemicolon)
        ? p.colonSemicolon
        : DEFAULT_PUNCTUATION_PAUSES.colonSemicolon,
  };
}

/**
 * Idempotent migration that synchronizes legacy default punctuation pauses across
 * all workspaces in localStorage (Dialogue, Dubbing, Batch, TTS) to the standard TTS defaults.
 */
export function migratePunctuationPauseDefaults(): void {
  if (typeof localStorage === "undefined") return;

  try {
    // 1. Dialogue settings
    const rawDialogue = localStorage.getItem("voxlab_dialogue_settings");
    if (rawDialogue) {
      try {
        const parsed = JSON.parse(rawDialogue);
        if (parsed && parsed.pauses && isLegacyPunctuationPauses(parsed.pauses)) {
          parsed.pauses = { ...DEFAULT_PUNCTUATION_PAUSES };
          localStorage.setItem("voxlab_dialogue_settings", JSON.stringify(parsed));
        }
      } catch {}
    }

    // 2. Dubbing voice settings
    const rawDubbing = localStorage.getItem("voxlab_dubbing_voice_settings");
    if (rawDubbing) {
      try {
        const parsed = JSON.parse(rawDubbing);
        if (parsed && parsed.pauses && isLegacyPunctuationPauses(parsed.pauses)) {
          parsed.pauses = { ...DEFAULT_PUNCTUATION_PAUSES };
          localStorage.setItem("voxlab_dubbing_voice_settings", JSON.stringify(parsed));
        }
      } catch {}
    }

    // 3. Batch global defaults
    const rawBatch = localStorage.getItem("voxlab_batch_global_defaults");
    if (rawBatch) {
      try {
        const parsed = JSON.parse(rawBatch);
        let batchUpdated = false;
        if (parsed.dialogue?.pauses && isLegacyPunctuationPauses(parsed.dialogue.pauses)) {
          parsed.dialogue.pauses = { ...DEFAULT_PUNCTUATION_PAUSES };
          batchUpdated = true;
        }
        if (parsed.dubbing?.pauses && isLegacyPunctuationPauses(parsed.dubbing.pauses)) {
          parsed.dubbing.pauses = { ...DEFAULT_PUNCTUATION_PAUSES };
          batchUpdated = true;
        }
        if (parsed.tts?.pauses && isLegacyPunctuationPauses(parsed.tts.pauses)) {
          parsed.tts.pauses = { ...DEFAULT_PUNCTUATION_PAUSES };
          batchUpdated = true;
        }
        if (batchUpdated) {
          localStorage.setItem("voxlab_batch_global_defaults", JSON.stringify(parsed));
        }
      } catch {}
    }

    // 4. TTS settings
    const rawTts = localStorage.getItem("voxlab_tts_settings");
    if (rawTts) {
      try {
        const parsed = JSON.parse(rawTts);
        if (parsed && parsed.pauses && isLegacyPunctuationPauses(parsed.pauses)) {
          parsed.pauses = { ...DEFAULT_PUNCTUATION_PAUSES };
          localStorage.setItem("voxlab_tts_settings", JSON.stringify(parsed));
        }
      } catch {}
    }
  } catch (err) {
    console.warn("Failed to migrate punctuation pause defaults:", err);
  }
}


