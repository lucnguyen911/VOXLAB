/**
 * Merges persisted voices from localStorage with the authoritative system catalog (`MOCK_VOICES`).
 * - Strips deprecated/demo voice IDs (`voice_01`..`voice_14`).
 * - Preserves user-created cloned voices (`origin === "clone"` or `source === "clone"`).
 * - Guarantees all current built-in Kokoro-82M, Edge TTS, and Google TTS voices are present.
 */
export function mergeStoredVoicesWithCatalog(
  stored: unknown,
  migrateFn: (v: VoiceProfile) => VoiceProfile = (v) => v
): VoiceProfile[] {
  const systemById = new Map<string, VoiceProfile>();
  for (const sysVoice of MOCK_VOICES) {
    systemById.set(sysVoice.id, migrateFn(sysVoice));
  }

  const customClones: VoiceProfile[] = [];
  const storedStateById = new Map<string, { isFavorite?: boolean; lastUsedAt?: string }>();

  if (Array.isArray(stored)) {
    for (const raw of stored) {
      if (!raw || typeof raw !== "object" || typeof (raw as any).id !== "string") continue;
      const v = raw as VoiceProfile;
      if (REMOVED_DEMO_VOICE_IDS.has(v.id)) continue;

      if (systemById.has(v.id)) {
        storedStateById.set(v.id, {
          isFavorite: v.isFavorite,
          lastUsedAt: v.lastUsedAt,
        });
      } else if (v.origin === "clone" || v.sourceType === "clone" || v.provider === "clone") {
        customClones.push(migrateFn(v));
      }
    }
  }

  const mergedSystem = Array.from(systemById.values()).map((sys) => {
    const prev = storedStateById.get(sys.id);
    if (!prev) return sys;
    return {
      ...sys,
      isFavorite: prev.isFavorite ?? sys.isFavorite,
      lastUsedAt: prev.lastUsedAt ?? sys.lastUsedAt,
    };
  });

  return [...customClones, ...mergedSystem];
}

